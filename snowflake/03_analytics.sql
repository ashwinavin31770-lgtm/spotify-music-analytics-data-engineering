-- Synthetic popularity score, not actual Spotify streaming popularity.
-- 1. Top tracks
SELECT TRACK_NAME, ARTIST_NAME, GENRE, POPULARITY
FROM GOLD_TOP_TRACKS ORDER BY POPULARITY DESC LIMIT 20;

-- 2. Artists with at least five tracks
SELECT ARTIST_NAME, TRACK_COUNT, AVG_POPULARITY, AVG_ENERGY
FROM GOLD_ARTIST_SUMMARY
WHERE TRACK_COUNT >= 5 ORDER BY AVG_POPULARITY DESC LIMIT 20;

-- 3. Genre comparison
SELECT GENRE, TRACK_COUNT, AVG_POPULARITY, AVG_ENERGY, AVG_DANCEABILITY
FROM GOLD_GENRE_SUMMARY ORDER BY AVG_POPULARITY DESC;

-- 4. Release-year trends
SELECT RELEASE_YEAR, TRACK_COUNT, AVG_POPULARITY
FROM GOLD_YEAR_SUMMARY ORDER BY RELEASE_YEAR;

-- 5. Popularity distribution
SELECT CASE
  WHEN POPULARITY >= 80 THEN '80-100'
  WHEN POPULARITY >= 60 THEN '60-79'
  WHEN POPULARITY >= 40 THEN '40-59'
  WHEN POPULARITY >= 20 THEN '20-39'
  ELSE '0-19' END AS POPULARITY_BAND,
  COUNT(*) AS TRACKS
FROM GOLD_TOP_TRACKS GROUP BY 1 ORDER BY 1;
