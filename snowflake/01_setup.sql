-- Replace placeholders. Execute using a role allowed to create storage integrations.
CREATE DATABASE IF NOT EXISTS SPOTIFY_DB;
CREATE SCHEMA IF NOT EXISTS SPOTIFY_DB.ANALYTICS;
CREATE WAREHOUSE IF NOT EXISTS SPOTIFY_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE STORAGE INTEGRATION IF NOT EXISTS SPOTIFY_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = S3
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::YOUR_AWS_ACCOUNT_ID:role/YOUR_SNOWFLAKE_ROLE'
  STORAGE_ALLOWED_LOCATIONS = ('s3://YOUR_BUCKET/curated/');

-- Run DESC INTEGRATION SPOTIFY_S3_INT.
-- Configure the AWS IAM trust policy with STORAGE_AWS_IAM_USER_ARN
-- and STORAGE_AWS_EXTERNAL_ID returned by DESC INTEGRATION.
CREATE STAGE IF NOT EXISTS SPOTIFY_CURATED_STAGE
  URL = 's3://YOUR_BUCKET/curated/'
  STORAGE_INTEGRATION = SPOTIFY_S3_INT
  FILE_FORMAT = (TYPE = PARQUET);
