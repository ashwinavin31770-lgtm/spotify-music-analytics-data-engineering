USE WAREHOUSE SPOTIFY_WH;
USE DATABASE SPOTIFY_DB;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE TABLE GOLD_TOP_TRACKS (
  TRACK_ID STRING, TRACK_NAME STRING, ARTIST_NAME STRING, GENRE STRING,
  RELEASE_DATE DATE, POPULARITY NUMBER(3,0), DANCEABILITY FLOAT,
  ENERGY FLOAT, TEMPO FLOAT, DURATION_MS NUMBER(10,0)
);
COPY INTO GOLD_TOP_TRACKS
FROM (
  SELECT $1:track_id::STRING, $1:track_name::STRING, $1:artist_name::STRING,
         $1:genre::STRING, $1:release_date::DATE, $1:popularity::NUMBER,
         $1:danceability::FLOAT, $1:energy::FLOAT, $1:tempo::FLOAT,
         $1:duration_ms::NUMBER
  FROM @SPOTIFY_CURATED_STAGE/top_tracks/
)
FILE_FORMAT = (TYPE = PARQUET);

CREATE OR REPLACE TABLE GOLD_ARTIST_SUMMARY (
  ARTIST_ID STRING, ARTIST_NAME STRING, TRACK_COUNT NUMBER,
  AVG_POPULARITY FLOAT, AVG_ENERGY FLOAT
);
COPY INTO GOLD_ARTIST_SUMMARY
FROM (
  SELECT $1:artist_id::STRING, $1:artist_name::STRING, $1:track_count::NUMBER,
         $1:avg_popularity::FLOAT, $1:avg_energy::FLOAT
  FROM @SPOTIFY_CURATED_STAGE/artist_summary/
)
FILE_FORMAT = (TYPE = PARQUET);

CREATE OR REPLACE TABLE GOLD_GENRE_SUMMARY (
  GENRE STRING, TRACK_COUNT NUMBER, AVG_POPULARITY FLOAT,
  AVG_ENERGY FLOAT, AVG_DANCEABILITY FLOAT
);
COPY INTO GOLD_GENRE_SUMMARY
FROM (
  SELECT $1:genre::STRING, $1:track_count::NUMBER, $1:avg_popularity::FLOAT,
         $1:avg_energy::FLOAT, $1:avg_danceability::FLOAT
  FROM @SPOTIFY_CURATED_STAGE/genre_summary/
)
FILE_FORMAT = (TYPE = PARQUET);

CREATE OR REPLACE TABLE GOLD_YEAR_SUMMARY (
  RELEASE_YEAR NUMBER(4,0), TRACK_COUNT NUMBER, AVG_POPULARITY FLOAT
);
COPY INTO GOLD_YEAR_SUMMARY
FROM (
  SELECT $1:release_year::NUMBER, $1:track_count::NUMBER, $1:avg_popularity::FLOAT
  FROM @SPOTIFY_CURATED_STAGE/year_summary/
)
FILE_FORMAT = (TYPE = PARQUET);
